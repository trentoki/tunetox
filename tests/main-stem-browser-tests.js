document.getElementById('run').addEventListener('click',async()=>{
  const result=document.getElementById('result');result.textContent='Running';
  const frame=document.getElementById('application'), w=frame.contentWindow, d=frame.contentDocument;
  const check=(v,m)=>{if(!v)throw new Error(m);};
  const wait=async condition=>{const deadline=performance.now()+5000;while(!condition()&&performance.now()<deadline)await new Promise(r=>setTimeout(r,20));check(condition(),'Timed out waiting for main application');};
  const change=(id,value)=>{const input=d.getElementById(id);input.value=value;input.dispatchEvent(new w.Event('change'));};
  const slide=(id,value)=>{const input=d.getElementById(id);input.value=value;input.dispatchEvent(new w.Event('input'));};
  let fileSequence=0;
  function file(){const frames=48000,bytes=new ArrayBuffer(44+frames*2),v=new DataView(bytes);
    const text=(at,s)=>{for(let i=0;i<s.length;i++)v.setUint8(at+i,s.charCodeAt(i));};
    text(0,'RIFF');v.setUint32(4,36+frames*2,true);text(8,'WAVE');text(12,'fmt ');v.setUint32(16,16,true);v.setUint16(20,1,true);v.setUint16(22,1,true);
    v.setUint32(24,48000,true);v.setUint32(28,96000,true);v.setUint16(32,2,true);v.setUint16(34,16,true);text(36,'data');v.setUint32(40,frames*2,true);
    return new w.File([bytes],'silent-stem-'+(++fileSequence)+'.wav',{type:'audio/wav'});}
  try{
    await wait(()=>!!w.eval('typeof mainStemIntegration !== "undefined"'));
    const router=w.eval('audioEngine'),state=w.eval('appState');
    const sections=d.querySelectorAll('#audio-decks > section');
    check(sections.length===4&&[1,2,3,4].every(id=>state.participation.byDeck[id].stemHandoff),'Four decks retain all participation defaults');
    check(router.getSourceMode(1)==='complete'&&router.getSourceMode(2)==='complete','Stem source is opt-in');
    for(const id of [1,2]){
      change('deck.'+id+'.sourceMode','stems');
      for(const name of ['transients','flow','tune','voice']){
        const input=d.getElementById('prototype.deck.'+id+'.stem.'+name+'.file'), transfer=new w.DataTransfer();transfer.items.add(file());input.files=transfer.files;input.dispatchEvent(new w.Event('change'));
      }
      d.getElementById('prototype.deck.'+id+'.load').click();
    }
    await wait(()=>router.getState(1).loaded&&router.getState(2).loaded);
    check(!router.setSourceMode(1,'complete'),'Loaded source cannot be switched');
    await wait(()=>!sections[0].querySelector('[data-action="play"]').disabled);
    check(sections[0].querySelector('[data-action="tempo"]').disabled,'Native stems disable unsupported tempo');
    slide('deck.1.volume',1);slide('deck.2.volume',1);slide('deck.2.stem.flow.level',0.5);
    check(state.decks[0].stems.allocatedLevels.flow===1,'Never-played preparation is isolated');
    await router.play(1);await router.play(2);
    check(Number(d.getElementById('deck.1.stem.flow.level').value)===0.5&&state.decks[0].stems.requestedLevels.flow===1,
      'Joining receiver fader updates immediately and preserves human request');
    slide('deck.2.stem.flow.level',0.7);
    check(Math.abs(Number(d.getElementById('deck.1.stem.flow.level').value)-0.3)<1e-12,'Live gesture refreshes receiver fader');
    slide('deck.2.stem.flow.level',0.5);
    await router.pause(2);const retained=JSON.stringify(state.decks.map(deck=>deck.stems));await router.play(2);
    check(JSON.stringify(state.decks.map(deck=>deck.stems))===retained,'Resume preserves allocations');
    sections[0].querySelector('[data-action="stop"]').click();
    check(!router.getState(1).isPlaying&&router.getState(2).isPlaying,'Existing transport buttons route exclusively and independently');
    // Replacement inherits state. No synthetic action is generated by decoding/loading.
    const before=JSON.stringify(state.stemSession.authorization);
    const files=Object.fromEntries(['transients','flow','tune','voice'].map(name=>[name,file()]));
    await router.loadStems(1,files);
    check(router.getState(1).levels.flow===0.5&&JSON.stringify(state.stemSession.authorization)===before,'Replacement preserves allocations/authorization');
    let finish;const slow={...files,transients:{arrayBuffer:()=>new Promise(resolve=>{finish=resolve;})}};
    const pending=router.loadStems(1,slow);await wait(()=>!!finish);await router.eject(1);
    check(!router.setSourceMode(1,'complete'),'Pending stale load blocks source switch after Eject');
    finish(await file().arrayBuffer());await pending;
    check(!router.getState(1).loaded&&router.setSourceMode(1,'complete'),'Stale result cannot restore ejected audio; completion unlocks switch');
    await router.eject(2);check(router.setSourceMode(2,'complete'),'Other deck can return to complete-song mode');
    await router.loadFile(2,file());await router.play(2);
    check(router.getState(2).loaded&&router.getState(2).isPlaying,'Normal complete-song playback still works after stem mode');
    await router.eject(2);
    // Deck 1 experimental selector remains usable with its original complete-song router.
    check(router.setMode('soundtouch')&&router.getMode()==='soundtouch'&&router.setMode('normal'),'Original experiment selector remains available');
    for(const backend of ['soundtouch','signalsmith']) {
      check(router.setMode(backend),'Can select existing backend after stem ejection');
      await router.loadFile(1,file());await router.play(1);
      check(router.getState(1).loaded&&router.getState(1).isPlaying,'Existing '+backend+' works through main source router');
      await router.stop(1);await router.eject(1);
      await wait(()=>!router.getState(1).closureBlocked&&!router.getState(1).loading);
    }
    check(router.setMode('normal'),'Existing router returns to Normal');
    await w.eval('mainStemIntegration.mixer.close()');
    frame.src='../experimental/four-stem-player.html';
    await wait(()=>{try{return w.eval('typeof stemPrototypeMixer !== "undefined"')&&frame.contentDocument.readyState==='complete';}catch(_){return false;}});
    check(frame.contentDocument.querySelectorAll('#decks > section').length===2,'Extracted component still mounts the prototype');
    await w.eval('stemPrototypeMixer.close()');
    result.textContent='Main stem integration tests passed: defaults, source guards, UI handoff, native transports, replacement, stale loads and cleanup.';
  }catch(error){result.textContent='FAIL: '+error.message;console.error(error);}
});
