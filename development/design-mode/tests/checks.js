/* Small checks shared by the command-line runner and browser fixture. */
function runStateChecks(model, samplerModel = globalThis.TuneToxDesign.samplerModel) {
  let count = 0;
  function check(value, message) { if (!value) throw new Error(message); count++; }
  const state = model.createState();
  check(state.decks.length === 4, 'four decks');
  check(!model.togglePlay(state, 3), 'empty deck cannot play');
  check(model.loadSelected(state, 3), 'load selected example');
  model.togglePlay(state, 3);
  check(state.decks[2].playing && !state.decks[0].playing, 'independent transport');
  const previous = state.decks[0].volume;
  model.setLevel(state, 3, null, 0.9);
  check(state.decks[0].volume === previous, 'independent levels');
  check(!model.setLevel(state, 3, null, NaN), 'invalid level rejected');
  check(!model.setLevel(state, 3, 9, 0.5), 'invalid stem rejected');
  model.setLevel(state, 3, 0, 0.2);
  check(state.decks[0].stems[0] !== 0.2, 'independent stem arrays');
  model.setSongQuery(state, 'nothing matches this');
  check(model.visibleSongs(state).length === 0 && !model.loadSelected(state, 4), 'empty search cannot load');
  model.setSongQuery(state, '');
  check(model.selectPlaylist(state, 'slow'), 'playlist selection');
  check(!model.selectSong(state, 'neon'), 'hidden song not selected');
  check(model.selectSong(state, 'after'), 'visible song selected');
  model.eject(state, 3);
  check(!state.decks[2].songId && !state.decks[2].playing, 'eject clears transport');
  check(model.createState().decks[2].songId === null, 'fresh session resets');
  check(model.setDeckControl(state, 3, 'tempo', 128), 'deck tempo updates');
  check(state.decks[0].tempo === 120 && state.tempo === 120, 'tempo remains independent');
  check(model.setDeckControl(state, 3, 'beatMatch', true), 'matching toggle');
  check(!state.decks[0].beatMatch, 'toggle scoped to deck');
  check(!model.setDeckControl(state, 3, 'pitch', 100), 'invalid pitch rejected');
  check(!model.setDeckControl(state, 3, 'face', 'back'), 'flip undefined');
  check(model.dropSong(state, 'neon', 'slow'), 'session playlist accepts song');
  check(!model.createState().playlists.find(p => p.id === 'slow').songIds.includes('neon'), 'example data stays immutable');
  model.dropSong(state, 'neon', 'slow');
  check(state.playlists.find(p => p.id === 'slow').songIds.filter(id => id === 'neon').length === 1, 'no duplicate memberships');
  check(!model.dropSong(state, 'invalid', 'link'), 'unknown drag rejected');
  check(model.dropSong(state, 'neon', 'link') && state.linkedSongId === 'neon', 'simulated link queue');
  check(model.setUserLink(state, 'neon', 'after', true), 'add manual link');
  check(!state.userLinks.after, 'links directional');
  check(!model.setUserLink(state, 'neon', 'neon', true), 'self-link rejected');
  check(!model.setUserLink(state, 'neon', 'unknown', true), 'unknown link rejected');
  model.setUserLink(state, 'neon', 'after', false);
  check(state.userLinks.neon.length === 0, 'remove manual link');
  check(model.setMembership(state, 'neon', 'slow', false), 'remove membership');
  check(!state.playlists.find(p => p.id === 'slow').songIds.includes('neon'), 'membership removed');
  check(!model.setMembership(state, 'neon', 'all', false), 'all examples immutable');
  check(model.createState().arrangement === 'slices' && model.createState().layout === 'full', 'modular slices default');
  check(model.setDeckControl(state, 1, 'sliceView', 'controls'), 'controls view accepted');
  check(state.decks[1].sliceView === 'waveform', 'independent deck view');
  check(!model.setDeckControl(state, 1, 'sliceView', 'invalid'), 'unknown view rejected');
  check(model.setDeckControl(state, 1, 'sliceView', 'waveform'), 'waveform view restored');
  check(model.setDeckControl(state, 2, 'columnMode', 'library'), 'column library mode accepted');
  check(state.decks[0].columnMode === 'waveform', 'column mode independent');
  check(!model.setDeckControl(state, 2, 'columnMode', 'unknown'), 'invalid column mode rejected');
  state.columnLibraries[0].songQuery = 'test';
  check(state.columnLibraries[1].songQuery === '', 'local library navigation independent');
  const matching = model.createState();
  matching.decks[0].beatMatch = matching.decks[1].beatMatch = true;
  matching.decks[0].tuneMatch = matching.decks[2].tuneMatch = true;
  check(model.adjustMatchedControl(matching, 1, 'tempo', 124), 'participant tempo gesture');
  check(matching.decks[1].tempo === 124 && matching.decks[2].tempo === 120, 'only Beat Match peers move');
  model.adjustMatchedControl(matching, 3, 'tempo', 126);
  check(matching.decks[0].tempo === 124 && matching.decks[2].tempo === 126, 'nonparticipant adjusts alone');
  model.adjustMatchedControl(matching, 1, 'pitch', 2);
  check(matching.decks[2].pitch === 2 && matching.decks[1].pitch === 0, 'only Tune Match peers move');
  matching.decks[2].pitch = 5;
  model.adjustMatchedControl(matching, 1, 'pitch', 6);
  check(matching.decks[0].pitch === 3 && matching.decks[2].pitch === 6, 'common delta bounded without changing offsets');
  check(!model.adjustMatchedControl(matching, 1, 'pitch', NaN) && !model.adjustMatchedControl(matching, 1, 'volume', .5), 'invalid matched gestures rejected');
  check(matching.tempo === 120 && matching.pitch === 0, 'no master tempo or pitch mutation');
  const sampled = model.createState();
  sampled.sampler.attenuation[0] = .65;
  const allocationBefore = JSON.stringify(sampled.decks);
  check(samplerModel.open(sampled, 2, 0), 'sampler source accepted');
  samplerModel.setLevel(sampled, 'attenuation', .2);
  check(JSON.stringify(sampled.decks) === allocationBefore, 'attenuation does not change handoff or stems');
  samplerModel.open(sampled, 3, 0);
  check(sampled.sampler.attenuation[0] === .2, 'same parent stem keeps attenuation session');
  samplerModel.open(sampled, 3, 1);
  check(sampled.sampler.attenuation[0] === .65, 'switch restores actual entry attenuation');
  sampled.sampler.attenuation[2] = .4;
  samplerModel.open(sampled, 1, 2); samplerModel.setLevel(sampled, 'attenuation', .1); samplerModel.close(sampled);
  check(sampled.sampler.attenuation[2] === .4 && !sampled.sampler.open, 'close restores attenuation session');
  check(!samplerModel.open(sampled, 9, 0) && !samplerModel.open(sampled, 1, 7), 'unknown sampler source rejected');
  check(!samplerModel.setLevel(sampled, 'outputVolume', .3), 'closed sampler ignores level gestures');
  samplerModel.open(sampled, 1, 0); samplerModel.setLevel(sampled, 'outputVolume', .3);
  check(sampled.sampler.outputVolume === .3 && sampled.sampler.attenuation[0] === .65, 'output volume independent');
  check(samplerModel.trigger(sampled, 24) && !samplerModel.trigger(sampled, 25), '25 pad bounds');
  samplerModel.syncKits(sampled);
  const lockedPadSong = sampled.sampler.kits[0].stems[0].songId;
  sampled.sampler.kits[0].stems[0].locked = true;
  sampled.decks[0].songId = 'after'; samplerModel.syncKits(sampled);
  check(sampled.sampler.kits[0].stems[0].songId === lockedPadSong && sampled.sampler.kits[0].stems[1].songId === 'after', 'stem kit lock preserves assignments');
  sampled.sampler.kits[0].songLocked = true;
  sampled.decks[0].songId = 'night'; samplerModel.syncKits(sampled);
  check(sampled.sampler.kits[0].songId === 'after' && sampled.sampler.kits[0].stems[1].songId === 'after', 'song kit lock preserves assignments');
  const phone = model.createState();
  check(model.selectPhoneDeck(phone, 4) && phone.phone.selectedDeckId === 4 && phone.editingDeckId === 4, 'phone deck selection');
  check(!model.selectPhoneDeck(phone, 8), 'unknown phone deck rejected');
  check(!model.setTransitionPair(phone, 0, 2) && model.setTransitionPair(phone, 0, 3), 'distinct transition pair enforced');
  check(!model.setTransitionPair(phone, 2, 4), 'unknown transition side rejected');
  check(model.setPerformanceControl(phone, 1, 'low', 6) && phone.decks[1].performance.eq.low === 0, 'EQ belongs to one deck');
  check(model.setPerformanceControl(phone, 1, 'filter', -.5) && !model.setPerformanceControl(phone, 1, 'filter', 2), 'bounded filter');
  check(model.setPerformanceControl(phone, 1, 'effectAssignment', 'Flanger', 0) && phone.decks[1].performance.effects[0].assignment === 'Echo', 'independent effect assignments');
  check(!model.setPerformanceControl(phone, 1, 'effectAssignment', 'unknown', 0) && !model.setPerformanceControl(phone, 1, 'effectValue', NaN, 0), 'invalid effect changes rejected');
  check(!model.setPerformanceControl(phone, 1, 'loopBeats', 0) && model.setPerformanceControl(phone, 1, 'loopBeats', .5), 'bounded loop preview');
  check(!model.setPerformanceControl(phone, 9, 'low', 1), 'unknown performance deck rejected');
  const navigation = model.createState(), originalPosition = navigation.decks[0].position;
  check(model.waveformGesture(navigation, 1, 'nudge', -1) && navigation.decks[0].waveformPreview.nudge === -1, 'preview nudge');
  check(model.waveformGesture(navigation, 1, 'navigation', .75) && navigation.decks[0].position === originalPosition, 'preview navigation leaves position unchanged');
  check(!model.waveformGesture(navigation, 1, 'navigation', 2) && !model.waveformGesture(navigation, 1, 'nudge', NaN), 'invalid waveform gestures rejected');
  check(navigation.decks[1].waveformPreview.navigation === 0, 'waveform previews independent');
  navigation.phone.mode = 'sampler'; samplerModel.open(navigation, 1, 0); model.selectPhoneDeck(navigation, 3);
  check(navigation.sampler.deckId === 3 && navigation.phone.pair[0] === 3 && navigation.phone.pair[1] !== 3, 'selected deck updates sampler source and anchored pair');
  check(['filter','high','mid','low'].every(key => model.getPerformanceNeutral(key) === (key === 'filter' ? model.createState().decks[0].performance.filter : model.createState().decks[0].performance.eq[key])), 'neutral values are shared with initial model state');
  check(model.getPerformanceNeutral('effectValue') === 0 && model.getPerformanceNeutral('unknown') === undefined, 'FX neutral and unsupported keys explicit');
  return count;
}
